const DICTS: Record<Lang, Dict> = { en, mr, hi };

export function t(lang: Lang, key: string): string {
  return DICTS[lang]?.[key] ?? DICTS.en[key] ?? key;
}

/** Every key a language has its own words for, so a test can look at all of them. */
export function keysOf(lang: Lang): string[] {
  return Object.keys(DICTS[lang]);
}

export function makeT(lang: Lang) {
  return (key: string) => t(lang, key);
}

export const LANG_NAMES: Record<Lang, string> = { en: 'English', mr: 'मराठी', hi: 'हिंदी' };

/** Replaces {name} placeholders. Used for every sentence that carries a number. */
export function fill(template: string, params: Record<string, string | number>): string {
  return Object.entries(params).reduce((s, [k, v]) => s.split(`{${k}}`).join(String(v)), template);
}

/** Devanagari digits (० to ९) as the digits the rest of the app writes (0 to 9), so a screen never mixes the two. */
export function latinDigits(text: string): string {
  return text.replace(/[\u0966-\u096F]/g, (d) => String(d.charCodeAt(0) - 0x0966));
}

/** A whole number as the app writes it, with a comma for thousands (1,714), the same on every device whatever its own language. */
export function numberText(n: number): string {
  const r = Math.round(n);
  const digits = String(Math.abs(r)).replace(/\B(?=(\d{3})+(?!\d))/g, ',');
  return r < 0 ? `-${digits}` : digits;
}
